export const LOCALE_CODES = LOCALES.map((l) => l.code);

export function isLocale(value: string | undefined | null): value is LocaleCode {
  return !!value && LOCALE_CODES.includes(value as LocaleCode);
}

export function localeMeta(code: LocaleCode): LocaleMeta {
  return LOCALES.find((l) => l.code === code) ?? LOCALES[0];
}

export function dirFor(code: LocaleCode): "rtl" | "ltr" {
  return localeMeta(code).dir;
}

export function detectLocale(acceptLanguage: string | null | undefined): LocaleCode {
  if (!acceptLanguage) return "ar";
  const parts = acceptLanguage
    .split(",")
    .map((chunk) => {
      const [tag, q] = chunk.trim().split(";q=");
      return { tag: tag.trim().toLowerCase(), q: q ? Number(q) : 1 };
    })
    .sort((a, b) => b.q - a.q);
  for (const part of parts) {
    const base = part.tag.split("-")[0];
    if (isLocale(base)) return base;
  }
  return "en";
}


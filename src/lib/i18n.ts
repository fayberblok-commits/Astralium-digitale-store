export function translate(locale: LocaleCode, key: MessageKey): string {
  if (locale === "ar") return ar[key];
  if (locale === "en") return en[key];
  return extras[locale]?.[key] ?? en[key];
}

export function createTranslator(locale: LocaleCode) {
  return (key: MessageKey) => translate(locale, key);
}

/** Content localiser: Arabic and English are first-class; other locales fall back to English. */
export function pickLocalized(
  locale: LocaleCode,
  arabic: string | null | undefined,
  english: string | null | undefined,
): string {
  if (locale === "ar") return arabic || english || "";
  return english || arabic || "";
}

